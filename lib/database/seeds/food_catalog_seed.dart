String _foodId(String suffix) => 'food-$suffix';
String _servingId(String suffix) => 'food-$suffix-default';
String _nutritionId(String suffix) => 'food-$suffix-default-nutrition';

/// Menyisipkan atau memperbarui katalog makanan bawaan berdasarkan pengenal
/// tetapnya (pola Design D2, change 004) — idempoten: menjalankannya
/// berkali-kali tidak pernah menggandakan baris maupun memutus tautan
/// catatan yang sudah dibuat terhadapnya (task 2.8).
Future<void> seedFoodCatalog(AppDatabase db) async {
  for (final seed in _kSeedFoods) {
    final foodId = _foodId(seed.idSuffix);
    final servingId = _servingId(seed.idSuffix);

    await db
        .into(db.foods)
        .insertOnConflictUpdate(
          FoodsCompanion.insert(
            id: foodId,
            createdAt: kFoodCatalogSeedTimestamp,
            updatedAt: kFoodCatalogSeedTimestamp,
            name: seed.name,
            category: seed.category.stableCode,
            isUserCreated: const Value<bool>(false),
            sourceType: const Value<String?>(_kSourceType),
            sourceRef: Value<String?>(seed.sourceRef),
            sourceVersion: const Value<String?>(_kSourceVersion),
            verifiedAt: Value<DateTime?>(kFoodCatalogSeedTimestamp),
          ),
        );

    await db
        .into(db.foodServings)
        .insertOnConflictUpdate(
          FoodServingsCompanion.insert(
            id: servingId,
            createdAt: kFoodCatalogSeedTimestamp,
            updatedAt: kFoodCatalogSeedTimestamp,
            foodId: foodId,
            label: seed.servingLabel,
            amount: seed.servingAmount,
            unit: seed.servingUnit,
            gramEquivalent: Value<double?>(seed.gramEquivalent),
            isDefault: const Value<bool>(true),
          ),
        );

    await db
        .into(db.nutritionValues)
        .insertOnConflictUpdate(
          NutritionValuesCompanion.insert(
            id: _nutritionId(seed.idSuffix),
            createdAt: kFoodCatalogSeedTimestamp,
            updatedAt: kFoodCatalogSeedTimestamp,
            servingId: servingId,
            energyKcal: Value<double?>(seed.energyKcal),
            proteinG: Value<double?>(seed.proteinG),
            carbohydrateG: Value<double?>(seed.carbohydrateG),
            fatG: Value<double?>(seed.fatG),
            fiberG: Value<double?>(seed.fiberG),
          ),
        );
  }
}
